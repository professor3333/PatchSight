"""The keyword-match baseline (proposal §10): a changed function is vulnerable when the
advisory names it.

A candidate counts as named when the advisory's summary or details contain its full name, or
the part after its last dot, as a whole word, case-sensitively. That is the rule E10 declared
before it was measured (``retrieval.named_in``); it is not tuned here. The candidates are
ChangedFuncs' own: every function the fix changed, after the path filter. So the two
baselines differ only in which candidates they keep, and both are scored against the same
labels, including true functions the fix did not change.

The retrieval bundles already hold, per candidate, its name and whether the advisory names
it, with no code and no advisory text (rule 13). ``score`` works from them and the labels
alone, so CI regenerates the committed report.
"""

from collections.abc import Mapping, Sequence, Set

from pydantic import BaseModel, ConfigDict

from patchsight.eval.metrics import SetScores, score
from patchsight.pipeline.benchmarks.retrieval import Case

BOOTSTRAP = 2000
SEED = 20261114  # the extraction reports' seed, so the intervals are drawn alike


def predicted(case: Case) -> set[str]:
    """Keyword match: the candidates the advisory names."""
    return {i.name for i in case.items if i.named}


def changed(case: Case) -> set[str]:
    """ChangedFuncs: every candidate."""
    return {i.name for i in case.items}


class SplitBaselines(BaseModel):
    model_config = ConfigDict(frozen=True)

    benchmark: str
    split: str
    reports: int
    names_a_candidate: int  # reports whose advisory names at least one changed function
    names_a_true_one: int  # ... at least one true vulnerable function among them
    keyword: SetScores
    changedfuncs: SetScores


def score_split(
    benchmark: str, split: str, cases: Sequence[Case], truth: Mapping[str, Set[str]]
) -> SplitBaselines:
    labels = {c.report: set(truth[c.report]) for c in cases}
    keyword = {c.report: predicted(c) for c in cases}
    return SplitBaselines(
        benchmark=benchmark,
        split=split,
        reports=len(cases),
        names_a_candidate=sum(1 for c in cases if keyword[c.report]),
        names_a_true_one=sum(1 for c in cases if keyword[c.report] & labels[c.report]),
        keyword=score(keyword, labels, BOOTSTRAP, SEED),
        changedfuncs=score({c.report: changed(c) for c in cases}, labels, BOOTSTRAP, SEED),
    )


class Source(BaseModel):
    model_config = ConfigDict(frozen=True)

    benchmark: str
    bundle: str  # repository path of the retrieval bundle
    bundle_sha256: str
    labels: str  # repository path of the labels


class Report(BaseModel):
    model_config = ConfigDict(frozen=True)

    bootstrap: int
    seed: int
    sources: tuple[Source, ...]
    splits: tuple[SplitBaselines, ...]


def splits_of(cases: Sequence[Case]) -> list[tuple[str, list[Case]]]:
    """``all``, then each split the cases carry, by name (one split: just it)."""
    names = sorted({c.split for c in cases})
    if len(names) == 1:
        return [(names[0], list(cases))]
    return [("all", list(cases)), *((n, [c for c in cases if c.split == n]) for n in names)]


LABELS = {"dunlap-v1": "Dunlap", "go-holdout-v1": "Go holdout"}
_SPLITS = {"all": "all", "dev": "dev", "test": "test", "holdout": ""}


def _label(s: SplitBaselines) -> str:
    split = _SPLITS.get(s.split, s.split)
    return f"{LABELS.get(s.benchmark, s.benchmark)}{', ' + split if split else ''}"


def _f1(s: SetScores) -> str:
    ci = s.f1_ci95
    return f"{s.f1:.3f}" + (f" ({ci.low:.2f} to {ci.high:.2f})" if ci else "")


def render_markdown(report: Report) -> str:
    lines = [
        "# Keyword-match baseline",
        "",
        "Generated by `python -m patchsight.pipeline keyword-baseline`; do not edit by hand.",
        "",
        "A changed function is marked vulnerable when the advisory's summary or details name "
        "it: its full name, or the part after its last dot, as a whole word, case-sensitively. "
        "This is the rule E10 declared before it was measured ([experiments](../experiments.md)); "
        "it is not tuned here. The candidates are ChangedFuncs' own, every function the fix "
        "changed after the path filter, and both are scored against the same labels. No model "
        "is called.",
        "",
        *(
            f"- {LABELS.get(s.benchmark, s.benchmark)}: bundle `{s.bundle}` SHA-256 "
            f"`{s.bundle_sha256}`; labels `{s.labels}`"
            for s in report.sources
        ),
        f"- Unit: (report, function). 95% CIs from {report.bootstrap:,} bootstrap resamples "
        f"of whole reports (seed {report.seed}).",
        "",
        "| Split | Reports | Names a changed function | Names a true one | Precision | Recall | "
        "F1 (95% CI) | Advisory miss rate | Exact match | ChangedFuncs F1 |",
        "|---|---:|---:|---:|---:|---:|---|---:|---:|---:|",
    ]
    for s in report.splits:
        k = s.keyword
        lines.append(
            f"| {_label(s)} | {s.reports} | {s.names_a_candidate} | {s.names_a_true_one} | "
            f"{k.precision:.3f} | {k.recall:.3f} | {_f1(k)} | {k.miss_rate:.1%} | "
            f"{k.exact_match:.1%} | {_f1(s.changedfuncs)} |"
        )
    lines += [
        "",
        "*Names a changed function* counts the reports whose advisory names at least one of "
        "the fix's changed functions; a report it names none of gets an empty prediction, "
        "which counts as a miss whenever the report has a true function.",
        "",
    ]
    return "\n".join(lines)
