"""uv.lock and poetry.lock parsing, lockfile discovery, and scanning a uv project."""

from pathlib import Path

import pytest
from typer.testing import CliRunner

from patchsight.cli import app
from patchsight.scan import lockfiles, run

UV_LOCK = """\
version = 1
requires-python = ">=3.12"

[[package]]
name = "PyYAML"
version = "5.3.1"
source = { registry = "https://pypi.org/simple" }
sdist = { url = "https://files.pythonhosted.org/pyyaml-5.3.1.tar.gz", hash = "sha256:00" }

[[package]]
name = "my-app"
version = "0.1.0"
source = { editable = "." }
dependencies = [{ name = "pyyaml" }]

[[package]]
name = "forked_lib"
version = "1.2.0"
source = { git = "https://github.com/o/forked-lib?rev=main#abc123" }

[[package]]
name = "vendored"
version = "0.0.1"
source = { path = "vendor/vendored-0.0.1.tar.gz" }
"""

POETRY_LOCK = """\
# This file is automatically @generated by Poetry and should not be changed by hand.

[[package]]
name = "Requests"
version = "2.31.0"
description = "Python HTTP for Humans."
optional = false
python-versions = ">=3.7"
files = []

[package.dependencies]
idna = ">=2.5,<4"

[[package]]
name = "internal-tool"
version = "3.0.0"
description = ""
optional = false
python-versions = "*"
files = []

[package.source]
type = "legacy"
url = "https://pypi.example.org/simple"
reference = "private"

[[package]]
name = "patched"
version = "1.0.0"
description = ""
optional = false
python-versions = "*"
files = []

[package.source]
type = "git"
url = "https://github.com/o/patched.git"
reference = "fix"
resolved_reference = "abc123"

[metadata]
lock-version = "2.0"
python-versions = "^3.12"
content-hash = "00"
"""


def _write(path: Path, text: str) -> Path:
    path.write_text(text, encoding="utf-8")
    return path


def test_uv_lock_pins_registry_packages_and_explains_the_rest(tmp_path: Path) -> None:
    found = {d.name: d for d in lockfiles.parse(_write(tmp_path / "uv.lock", UV_LOCK))}
    assert (found["pyyaml"].version, found["pyyaml"].raw_name) == ("5.3.1", "PyYAML")
    assert found["pyyaml"].line == 4  # the [[package]] header
    assert found["pyyaml"].unpinned_reason is None
    assert found["my-app"].unpinned_reason == "the project itself or a workspace member"
    assert (found["forked-lib"].version, found["forked-lib"].unpinned_reason) == (
        None,
        "git source",
    )
    assert found["vendored"].unpinned_reason == "local path source"


def test_poetry_lock_keeps_alternative_indexes_and_explains_git(tmp_path: Path) -> None:
    found = {d.name: d for d in lockfiles.parse(_write(tmp_path / "poetry.lock", POETRY_LOCK))}
    assert (found["requests"].version, found["requests"].line) == ("2.31.0", 3)
    assert found["internal-tool"].version == "3.0.0"
    assert (found["patched"].version, found["patched"].unpinned_reason) == (None, "git source")
    assert "idna" not in found  # a dependency table, not a locked package


def test_each_package_points_at_its_header_however_written(tmp_path: Path) -> None:
    """A comment after the header, or spaces inside its brackets, once gave line 0 and moved
    every later package's evidence line (found by tests/test_scan_properties.py)."""
    text = ('version = 1\n\n[[package]]  # pinned for a reason\nname = "a"\nversion = "1.0"\n'
            '\n[[ package ]]\nname = "b"\nversion = "2.0"\n')  # fmt: skip
    parsed = lockfiles.parse(_write(tmp_path / "uv.lock", text))
    found = [(d.name, d.version, d.line) for d in parsed]
    assert found == [("a", "1.0", 3), ("b", "2.0", 7)]


def test_invalid_toml_is_a_clear_error(tmp_path: Path) -> None:
    with pytest.raises(ValueError, match="not valid TOML"):
        lockfiles.parse(_write(tmp_path / "uv.lock", "[[package]\nname = "))


def test_discovery_prefers_requirements_then_uv_then_poetry(tmp_path: Path) -> None:
    assert lockfiles.find(tmp_path) is None
    _write(tmp_path / "poetry.lock", POETRY_LOCK)
    assert lockfiles.find(tmp_path) == tmp_path / "poetry.lock"
    _write(tmp_path / "uv.lock", UV_LOCK)
    assert lockfiles.find(tmp_path) == tmp_path / "uv.lock"
    _write(tmp_path / "requirements.txt", "x==1\n")
    assert lockfiles.find(tmp_path) == tmp_path / "requirements.txt"


def test_scan_finds_a_uv_lock_and_queries_only_pinned_packages(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    _write(tmp_path / "uv.lock", UV_LOCK)
    _write(tmp_path / "app.py", "import yaml\n")
    queried: list[list[tuple[str, str]]] = []

    def fake_query(
        packages: list[tuple[str, str]], client: object = None
    ) -> dict[object, list[str]]:
        queried.append(packages)
        return {}

    monkeypatch.setattr(run.osv_client, "query", fake_query)
    database = tmp_path / "missing.sqlite"
    result = CliRunner().invoke(app, ["scan", str(tmp_path), "--db", str(database)])
    assert queried == [[("pyyaml", "5.3.1")]]  # git, path and the project itself are not
    assert result.exit_code == 2  # no database here, after the lockfile was read
    explicit = CliRunner().invoke(
        app, ["scan", str(tmp_path), "--lockfile", str(tmp_path / "none.lock")]
    )
    assert explicit.exit_code == 2
    assert "no lockfile at" in explicit.output
