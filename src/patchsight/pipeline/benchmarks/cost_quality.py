"""Cost against quality on the Dunlap dev split (proposal §10's selection rule).

For each extraction configuration measured on dev: F1, and input and output tokens per
report, from its committed extraction report. The proposal's rule chooses the cheapest
configuration (fewest tokens per report) within 2 F1 points of the best. The price per
1,000 reports at the provider's published rates (``configs/pricing.toml``) is shown too,
since tokens of different models do not cost the same.

Everything comes from committed reports, so CI regenerates the table and the chart.
"""

from pathlib import Path

from pydantic import BaseModel, ConfigDict

from patchsight.pipeline.benchmarks.extraction import ExtractionRun

# The configurations measured on dev, in the order they were run. Variants that change
# only validation (dotted entry points) send the same prompts, so they are left out.
CONFIGURATIONS: tuple[tuple[str, str], ...] = (
    ("Qwen3.8-27B 4-bit, Kaggle", "extract-v1-qwen3.8-27b-q4km"),
    ("Qwen3.8-27B, Groq", "extract-v1-qwen3.8-27b"),
    ("Qwen3.8-27B, Groq, 14-candidate cap", "extract-v1-qwen3.8-27b-cap105"),
    ("gpt-oss-120b, Groq", "extract-v1-gpt-oss-120b"),
    ("gpt-oss-20b, Kaggle", "extract-v1-gpt-oss-20b-mxfp4"),
)
# Shorter names for the chart's direct labels; the table keeps the full ones.
SHORT = {
    "Qwen3.8-27B 4-bit, Kaggle": "Qwen 4-bit, Kaggle",
    "Qwen3.8-27B, Groq": "Qwen, Groq",
    "Qwen3.8-27B, Groq, 14-candidate cap": "Qwen, Groq, capped",
}
WITHIN = 0.02  # "within 2 F1 points of the best"


class Point(BaseModel):
    model_config = ConfigDict(frozen=True)

    label: str
    tag: str
    model: str
    f1: float
    precision: float
    recall: float
    prompt_tokens: float  # per report
    completion_tokens: float
    usd_per_1000: float | None  # at the published rates, priced as the hosted model

    @property
    def tokens(self) -> float:
        return self.prompt_tokens + self.completion_tokens


class CostQuality(BaseModel):
    model_config = ConfigDict(frozen=True)

    reports: int
    points: tuple[Point, ...]
    changedfuncs_f1: float
    best: str
    chosen: str
    pricing_source: str | None
    pricing_retrieved: str | None


def measure(reports_dir: Path, prices: dict[str, tuple[float, float]] | None = None,
            source: str | None = None, retrieved: str | None = None) -> CostQuality:  # fmt: skip
    """``prices``: per model as its report names it, input and output dollars per million."""
    points, counts, changedfuncs = [], set(), 0.0
    for label, tag in CONFIGURATIONS:
        run = ExtractionRun.model_validate_json(
            (reports_dir / f"extraction-dunlap-dev-{tag}.json").read_text("utf-8")
        )
        counts.add(run.reports)
        changedfuncs = run.changedfuncs.f1
        prompt, completion = run.prompt_tokens / run.reports, run.completion_tokens / run.reports
        price = (prices or {}).get(run.model)
        usd = None if price is None else (prompt * price[0] + completion * price[1]) / 1000
        points.append(Point(
            label=label, tag=tag, model=run.model, f1=run.extraction.f1,
            precision=run.extraction.precision, recall=run.extraction.recall,
            prompt_tokens=prompt, completion_tokens=completion,
            usd_per_1000=None if usd is None else round(usd, 4),
        ))  # fmt: skip
    if len(counts) != 1:
        raise ValueError(f"the reports cover different numbers of dev reports: {sorted(counts)}")
    best = max(points, key=lambda p: p.f1)
    close = [p for p in points if p.f1 >= best.f1 - WITHIN]
    chosen = min(close, key=lambda p: (p.tokens, p.label))
    return CostQuality(
        reports=counts.pop(), points=tuple(points), changedfuncs_f1=changedfuncs,
        best=best.label, chosen=chosen.label, pricing_source=source, pricing_retrieved=retrieved,
    )  # fmt: skip


def render_markdown(result: CostQuality, image: str) -> str:
    r = result
    lines = [
        "# Cost against quality: Dunlap dev split",
        "",
        "Generated by `python -m patchsight.pipeline cost-quality`; do not edit by hand.",
        "",
        f"Every extraction configuration measured on the {r.reports} dev reports, from its "
        "committed extraction report. The proposal's rule chooses the cheapest configuration, "
        "by tokens per report, within 2 F1 points of the best.",
        "",
        f"![F1 against tokens per report, one point per configuration]({image})",
        "",
        "| Configuration | F1 | Precision | Recall | Input tokens per report | "
        "Output tokens per report | At paid rates, per 1,000 reports |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for p in r.points:
        usd = "—" if p.usd_per_1000 is None else f"${p.usd_per_1000:,.2f}"
        mark = " **(chosen)**" if p.label == r.chosen else ""
        lines.append(
            f"| {p.label}{mark} | {p.f1:.3f} | {p.precision:.3f} | {p.recall:.3f} | "
            f"{p.prompt_tokens:,.0f} | {p.completion_tokens:,.0f} | {usd} |"
        )
    lines += [
        f"| ChangedFuncs (every changed function, no model) | {r.changedfuncs_f1:.3f} | | | 0 "
        "| 0 | $0.00 |",
        "",
        f"**Chosen: {r.chosen}.** It has the best F1, and no other configuration comes within "
        "2 points of it, so the rule picks it whatever its tokens."
        if r.chosen == r.best
        else f"**Chosen: {r.chosen}**, the cheapest within 2 F1 points of {r.best}.",
        "",
        "Tokens per report barely differ between configurations, because every role shares one "
        "prompt budget; what they cost differs more, by model.",
    ]
    if r.pricing_source:
        lines += [
            "",
            f"Paid rates: the provider's published on-demand prices ({r.pricing_source}, read "
            f"{r.pricing_retrieved}); a self-hosted model is priced as the hosted model it "
            "stands for.",
        ]
    lines.append("")
    return "\n".join(lines)


# The chart: one axis each way, the chosen point ringed, the 2-point band shaded.
_STYLE = """
  .surface { fill: #fcfcfb; } .ink { fill: #0b0b0b; } .ink2 { fill: #52514e; }
  .muted { fill: #898781; } .grid { stroke: #e1e0d9; } .axis { stroke: #c3c2b7; }
  .band { fill: #2a78d6; fill-opacity: 0.08; } .dot { fill: #2a78d6; stroke: #fcfcfb; }
  .ring { fill: none; stroke: #0b0b0b; }
  @media (prefers-color-scheme: dark) {
    .surface { fill: #1a1a19; } .ink { fill: #f0efec; } .ink2 { fill: #c3c2b7; }
    .grid { stroke: #2c2c2a; } .axis { stroke: #383835; }
    .band { fill: #3987e5; fill-opacity: 0.14; } .dot { fill: #3987e5; stroke: #1a1a19; }
    .ring { stroke: #f0efec; }
  }
  text { font-family: system-ui, -apple-system, "Segoe UI", sans-serif; }
"""


def _escape(text: str) -> str:
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def render_svg(result: CostQuality) -> str:
    width, height = 720, 420
    left, right, top, bottom = 64, 24, 48, 56
    xs = [p.tokens for p in result.points]
    ys = [p.f1 for p in result.points]
    x0, x1 = (min(xs) // 50) * 50 - 50, (max(xs) // 50) * 50 + 100
    y0, y1 = round(min(ys) - 0.03, 2), round(max(ys) + 0.02, 2)

    def sx(v: float) -> float:
        return left + (v - x0) / (x1 - x0) * (width - left - right)

    def sy(v: float) -> float:
        return height - bottom - (v - y0) / (y1 - y0) * (height - top - bottom)

    best = max(ys)
    parts = [
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {height}" '
        f'width="{width}" height="{height}" role="img" '
        'aria-label="F1 against tokens per report on the Dunlap dev split">',
        f"<style>{_STYLE}</style>",
        f'<rect class="surface" width="{width}" height="{height}" rx="8"/>',
        f'<text class="ink" x="{left}" y="28" font-size="15" font-weight="600">F1 against '
        "tokens per report, Dunlap dev split</text>",
        f'<rect class="band" x="{left}" y="{sy(best):.1f}" width="{width - left - right}" '
        f'height="{sy(best - WITHIN) - sy(best):.1f}"/>',
        f'<text class="ink2" x="{width - right - 6}" y="{sy(best - WITHIN) - 6:.1f}" '
        'font-size="11" text-anchor="end">within 2 F1 points of the best</text>',
    ]
    step = 0.02
    tick = y0
    while tick <= y1 + 1e-9:
        y = sy(tick)
        parts += [
            f'<line class="grid" x1="{left}" x2="{width - right}" y1="{y:.1f}" y2="{y:.1f}" '
            'stroke-width="1"/>',
            f'<text class="muted" x="{left - 8}" y="{y + 4:.1f}" font-size="11" '
            f'text-anchor="end">{tick:.2f}</text>',
        ]
        tick = round(tick + step, 2)
    tick = x0
    while tick <= x1:
        x = sx(tick)
        parts.append(
            f'<text class="muted" x="{x:.1f}" y="{height - bottom + 18}" font-size="11" '
            f'text-anchor="middle">{tick:,.0f}</text>'
        )
        tick += 50
    parts += [
        f'<line class="axis" x1="{left}" x2="{width - right}" y1="{height - bottom}" '
        f'y2="{height - bottom}" stroke-width="1"/>',
        f'<text class="ink2" x="{(left + width - right) / 2}" y="{height - 14}" font-size="12" '
        'text-anchor="middle">tokens per report (input and output)</text>',
        f'<text class="ink2" x="16" y="{(top + height - bottom) / 2}" font-size="12" '
        f'text-anchor="middle" transform="rotate(-90 16 {(top + height - bottom) / 2})">'
        "F1</text>",
    ]
    placed = [(sx(p.tokens), sy(p.f1)) for p in result.points]
    for p, (x, y) in zip(result.points, placed, strict=True):
        if p.label == result.chosen:
            parts.append(
                f'<circle class="ring" cx="{x:.1f}" cy="{y:.1f}" r="9" stroke-width="1.5"/>'
            )
        parts.append(f'<circle class="dot" cx="{x:.1f}" cy="{y:.1f}" r="5" stroke-width="2"/>')
    for p, (x, y) in zip(result.points, placed, strict=True):
        text = SHORT.get(p.label, p.label) + (" (chosen)" if p.label == result.chosen else "")
        wide = 6.6 * len(text) + 12  # about 6.6 px a character at 12 px
        # Right of the dot, unless that runs off the plot or into a neighbour at the same
        # height on the right; then left of it; and below it when neither side fits.
        crowded = any(abs(oy - y) < 14 and 0 < ox - x < wide for ox, oy in placed)
        if not crowded and x + wide <= width - right:
            lx, ly, anchor = x + 12, y + 4, "start"
        elif x - wide >= left:
            lx, ly, anchor = x - 12, y + 4, "end"
        else:
            lx, ly, anchor = x, y + 22, "middle"
        parts.append(
            f'<text class="ink" x="{lx:.1f}" y="{ly:.1f}" font-size="12" '
            f'text-anchor="{anchor}">{_escape(text)}</text>'
        )
    parts.append("</svg>")
    return "\n".join(parts) + "\n"
